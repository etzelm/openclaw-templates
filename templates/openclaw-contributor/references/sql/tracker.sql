-- Regenerate tracker.md from the database. No input. Overwrites tracker.md.
-- Run from the workspace root:
--   sqlite3 -bail <db_path> ".read references/sql/tracker.sql"
.bail on
PRAGMA foreign_keys = ON;
CREATE TEMP TABLE schema_guard (v INTEGER CHECK (v = 3));
INSERT INTO temp.schema_guard SELECT user_version FROM pragma_user_version;

.headers on
.output tracker.md
.print "# Contributions tracker"
.print ""
.print "Generated from the database at db_path. Do not edit this file: the next update overwrites it."
.print "The database is the source of truth. To change a row, ask the agent."
.print ""
.print "## Contributions"
.print ""
.mode markdown
SELECT
  k.id AS id,
  k.slug AS slug,
  c.url AS issue,
  k.status AS status,
  replace(k.branch, '|', '/') AS branch,
  substr(k.head_sha, 1, 12) AS head,
  k.pr_url AS pr,
  coalesce((SELECT e.kind || ' ' || e.result || ' at ' || substr(e.commit_sha, 1, 12)
            FROM evidence AS e WHERE e.contribution_id = k.id
            ORDER BY e.recorded_at DESC, e.id DESC LIMIT 1), '') AS "last evidence",
  coalesce((SELECT group_concat(a.action, ', ') FROM approvals AS a
            WHERE a.contribution_id = k.id AND a.decision = 'pending'), '') AS "waiting for owner",
  coalesce((SELECT 'grant ' || g.id || ': ' || replace(replace(replace(g.actions, '"', ''), '[', ''), ']', '')
            FROM grants AS g WHERE g.contribution_id = k.id AND g.ended_at IS NULL), '') AS "standing grant",
  replace(replace(k.note, '|', '/'), char(10), ' ') AS note,
  k.updated_at AS updated
FROM contributions AS k
JOIN candidates AS c ON c.id = k.candidate_id
ORDER BY k.updated_at DESC, k.id DESC;
.mode list
.headers off
.print ""
.print "## Candidates considered"
.print ""
.headers on
.mode markdown
SELECT
  c.url AS issue,
  replace(replace(c.title, '|', '/'), char(10), ' ') AS title,
  replace(c.area, '|', '/') AS area,
  c.decision AS decision,
  replace(replace(c.reason, '|', '/'), char(10), ' ') AS reason,
  json_array_length(c.related) AS related,
  c.updated_at AS updated
FROM candidates AS c
ORDER BY c.updated_at DESC, c.id DESC;
.output stdout
.mode list
.headers off
SELECT 'tracker.md regenerated: ' || (SELECT count(*) FROM contributions) || ' contributions, '
       || (SELECT count(*) FROM candidates) || ' candidates' AS result;
