-- Regenerate tracker.md from the database at the end of every run. No input. Overwrites tracker.md.
-- Run from the workspace root:
--   sqlite3 -bail applications.db ".read references/sql/tracker.sql"
.bail on
PRAGMA foreign_keys = ON;
CREATE TEMP TABLE schema_guard (v INTEGER CHECK (v = 1));
INSERT INTO temp.schema_guard SELECT user_version FROM pragma_user_version;

.headers on
.output tracker.md
.print "# Tracker"
.print ""
.print "Generated from applications.db at the end of each run. Do not edit this file: the next run overwrites it."
.print "applications.db is the source of truth. To change a status, ask the agent, or see the one-line command in references/apply-loop.md."
.print ""
.mode markdown
SELECT
  a.day AS date,
  replace(replace(p.company, '|', '/'), char(10), ' ') AS company,
  replace(replace(p.title, '|', '/'), char(10), ' ') AS title,
  p.link AS link,
  replace(replace(p.fit_reason, '|', '/'), char(10), ' ') AS "fit reason",
  coalesce((SELECT group_concat(replace(replace(x.field_label, '|', '/'), char(10), ' '), '; ')
            FROM answers AS x WHERE x.application_id = a.id AND x.flagged = 1), '') AS "flagged answers",
  a.status AS status,
  replace(replace(a.note, '|', '/'), char(10), ' ') AS note,
  CASE WHEN length(p.job_description) > 120
       THEN trim(substr(replace(replace(replace(p.job_description, '|', '/'), char(13), ' '), char(10), ' '), 1, 120)) || '...'
       ELSE trim(replace(replace(replace(p.job_description, '|', '/'), char(13), ' '), char(10), ' '))
  END AS "description excerpt"
FROM applications AS a
JOIN postings AS p ON p.id = a.posting_id
ORDER BY a.day DESC, a.id DESC;
.output stdout
.mode list
.headers off
SELECT 'tracker.md regenerated: ' || count(*) || ' rows' AS result FROM applications;
